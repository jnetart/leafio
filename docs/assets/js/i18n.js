function detectLang() {
  const saved = localStorage.getItem('leafio-lang');
  if (saved === 'zh' || saved === 'en') return saved;
  return (navigator.language || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

function applyLang(lang) {
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (I18N[key] && I18N[key][lang]) el.textContent = I18N[key][lang];
  });
  const t = document.querySelector('title[data-i18n]');
  if (t && I18N[t.getAttribute('data-i18n')] && I18N[t.getAttribute('data-i18n')][lang]) t.textContent = I18N[t.getAttribute('data-i18n')][lang];
  document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    const key = el.getAttribute('data-i18n-alt');
    if (I18N[key] && I18N[key][lang]) el.setAttribute('alt', I18N[key][lang]);
  });
  document.querySelectorAll('.lang-switch button').forEach((b) => {
    b.classList.toggle('active', b.dataset.lang === lang);
  });
  localStorage.setItem('leafio-lang', lang);
}

document.addEventListener('DOMContentLoaded', () => {
  const lang = detectLang();
  document.querySelectorAll('.lang-switch button').forEach((b) => {
    b.addEventListener('click', () => applyLang(b.dataset.lang));
  });
  applyLang(lang);
});
